-- ONE-TIME secure banner synchronization migration.
-- Run in the SAME Supabase project as shop.shanmukiorg.workers.dev.
-- Does not delete existing banner records or change their active state.
create table if not exists public.banners (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  link text,
  image text not null,
  position text not null default 'hero',
  "order" integer not null default 1,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists banners_slug_unique_sync on public.banners (slug);
create index if not exists banners_position_active_sort on public.banners (position, active, "order");

-- Lock writes to the verified-admin Edge Function; a normal signed-in customer
-- MUST NOT be able to publish/pause a banner through the public API.
alter table public.banners enable row level security;
drop policy if exists "banners_select_active" on public.banners;
drop policy if exists "banners_insert_auth" on public.banners;
drop policy if exists "banners_update_auth" on public.banners;
drop policy if exists "banners_delete_auth" on public.banners;
drop policy if exists "banners_public_active_select_v2" on public.banners;
create policy "banners_public_active_select_v2" on public.banners
  for select to anon, authenticated using (active is true);
revoke all on public.banners from anon, authenticated;
grant select on public.banners to anon, authenticated;
grant select, insert, update, delete on public.banners to service_role;
-- The service-role Edge Function inserts new banner identity rows.
do $$ declare seq_name text; begin
  seq_name := pg_get_serial_sequence('public.banners', 'id');
  if seq_name is not null then
    execute format('grant usage, select on sequence %s to service_role', seq_name);
  end if;
end $$;
